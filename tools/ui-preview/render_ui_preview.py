def draw_screen(width, height, tokens, table, scale, settings_open=False, hover_card=1,
                selected_card=0, hover_toolbar=None):
    cv = Canvas(width, height, scale)
    cv.fill(0, 0, width, height, tokens["background"])

    # ---- header (mirrors StudioScreen.init/drawHeader) ----------------------
    cv.panel(4, 4, width - 8, HEADER_HEIGHT - 4, tokens["panel"], tokens["border"])
    cursor = 10
    name_w = min(120, max(60, width // 3))
    field(cv, cursor, 10, name_w, 18, PROFILES[0][0], tokens)
    cursor += name_w + 6
    needed = HEADER_BUTTON * 3 + 12 + HEADER_SMALL * 5 + 12
    compact = cursor + needed > width - 12
    primary = HEADER_BUTTON if not compact else max(28, min(HEADER_BUTTON, (width - cursor - 64) // 3))
    for label_key, short_key, state in (("run.stop", "run.stopShort", "accent"),
                                        ("run.pause", "run.pauseShort", "normal"),
                                        ("macro.new", "macro.newShort", "normal")):
        key = short_key if compact else label_key
        label = ellipsize(cv, tr(table, key), primary - 8)
        button(cv, cursor, 10, primary, TOOLBAR_H, label, tokens, state)
        cursor += primary + 4
    if not compact:
        shorts = {"action.copyShort": "profile.copy", "action.deleteShort": "action.delete",
                  "action.profilesShort": "profile.toggleList", "action.sortShort": "profile.sort",
                  "action.settingsShort": "action.settings"}
        for short_key in shorts:
            state = "accent" if short_key == "action.settingsShort" and settings_open else "normal"
            if hover_toolbar == short_key:
                state = "hover"
            label = ellipsize(cv, tr(table, short_key), HEADER_SMALL - 8)
            button(cv, cursor, 10, HEADER_SMALL, TOOLBAR_H, label, tokens, state)
            cursor += HEADER_SMALL + 4
    else:
        button(cv, width - 40, 10, 30, TOOLBAR_H, ellipsize(cv, tr(table, "action.menu"), 22),
               tokens, "accent" if settings_open else "normal")

    label_y = HEADER_HEIGHT - 11
    title = ellipsize(cv, tr(table, "screen.title"), max(40, width - 24 - 60))
    cv.text(10, label_y, title, tokens["mutedText"])
    status = tr(table, "state.running")
    cv.text(max(10, width - 12 - cv.width(status)), label_y, status, tokens["success"])

    # ---- profile column ---------------------------------------------------
    body_top = HEADER_HEIGHT + 6
    body_h = height - HEADER_HEIGHT - FOOTER_HEIGHT - 12
    narrow = width < 420
    col_w = 0 if narrow else PROFILE_COLUMN
    if col_w:
        field(cv, 12, body_top, PROFILE_COLUMN - 14, 18, "", tokens,
              hint=tr(table, "profile.search"))
        list_top = body_top + 24
        cv.panel(10, list_top, col_w, body_h - 24, tokens["backgroundAlt"], tokens["border"])
        row_h = ROW_HEIGHT
        for i, (name, count, selected) in enumerate(PROFILES):
            ry = list_top + 4 + i * row_h
            if ry + row_h > list_top + body_h - 24:
                break
            row_tint = composite(tokens["selection"], tokens["backgroundAlt"]) if selected \
                else tokens["backgroundAlt"]
            text_on_row = enforce_contrast(tokens["normalText"], row_tint, 7.0)
            muted_on_row = enforce_contrast(tokens["mutedText"], row_tint, 4.5)
            cv.fill(12, ry, col_w - 4, row_h - 2, row_tint)
            if selected:
                cv.fill(12, ry, 2, row_h - 2, tokens["accent"])
            cv.text(20, ry + 4, name, text_on_row, max_width=col_w - 26)
            cv.text(20, ry + 15, tr(table, "profile.row.macros", count), muted_on_row)

    # ---- macro cards ------------------------------------------------------
    column_x = 10 + col_w + 6 if col_w else 10
    editor_w = 0 if width < 420 + EDITOR_COLUMN else EDITOR_COLUMN
    available = max(120, width - column_x - (editor_w + 16))
    cv.panel(column_x - 4, body_top - 4, available + 8, body_h + 8,
             tokens["backgroundAlt"], tokens["border"])
    y = body_top
    for i, (name, kind, content, interval, enabled, state, next_in) in enumerate(MACROS):
        if y + CARD_HEIGHT > body_top + body_h:
            break
        selected = i == selected_card
        surface = tokens["raisedPanel"] if i == hover_card else tokens["panel"]
        if selected:
            surface = composite(tokens["accentSoft"], surface)
        cv.panel(column_x, y, available, CARD_HEIGHT, surface,
                 tokens["accent"] if selected else tokens["border"])
        if selected:
            cv.fill(column_x, y, 2, CARD_HEIGHT, tokens["accent"])
        text_x = column_x + 10
        max_name = available - TOGGLE_W - 96
        cv.text(text_x, y + 7, name, enforce_contrast(tokens["normalText"], surface, 7.0),
                max_width=max(20, max_name))
        type_key = "macro.type.command" if kind == "command" else "macro.type.chat"
        pill_fill = tokens["warning"] if kind == "command" else composite(tokens["accentSoft"], surface)
        pw = pill(cv, text_x, y + 20, 12, tr(table, type_key), pill_fill, tokens["normalText"])
        preview_x = text_x + pw + 6
        cv.text(preview_x, y + 22, content, tokens["mutedText"],
                max_width=max(20, available - (preview_x - column_x) - TOGGLE_W - 24))
        meta = tr(table, "macro.card.interval", interval)
        if next_in:
            meta += "  ·  " + tr(table, "macro.card.nextIn", next_in)
        cv.text(text_x, y + 33, meta, tokens["mutedText"], max_width=max(20, available - 120))
        state_color = tokens["success"] if enabled else tokens["mutedText"]
        if state == "Bekletiliyor":
            state_color = tokens["warning"]
        cv.text(column_x + available - TOGGLE_W - 14 - cv.width(tr(table, "state." +
                {"Açık": "enabled", "Kapalı": "disabled", "Çalışıyor": "running",
                 "Bekletiliyor": "held"}[state])), y + 8,
                tr(table, "state." + {"Açık": "enabled", "Kapalı": "disabled",
                                      "Çalışıyor": "running", "Bekletiliyor": "held"}[state]),
                state_color)
        tx = column_x + available - TOGGLE_W - 8
        ty = y + (CARD_HEIGHT - TOGGLE_H) // 2 + 6
        cv.panel(tx, ty, TOGGLE_W, TOGGLE_H,
                 tokens["accent"] if enabled else tokens["fieldBackground"],
                 tokens["borderStrong"], corner=TOGGLE_H // 2)
        knob = tx + TOGGLE_W - TOGGLE_H + 1 if enabled else tx + 1
        cv.panel(knob, ty + 1, TOGGLE_H - 2, TOGGLE_H - 2, tokens["normalText"], 0,
                 corner=(TOGGLE_H - 2) // 2)
        y += CARD_HEIGHT + CARD_GAP

    # ---- editor column ----------------------------------------------------
    ex = width - editor_w - 10 if editor_w else column_x
    ew = editor_w if editor_w else max(160, available)
    ey = body_top
    eh = max(120, height - HEADER_HEIGHT - 12)
    bottom_limit = height - FOOTER_HEIGHT
    cv.shadow(ex, ey, ew, eh, composite(tokens["shadow"], tokens["background"]))
    cv.panel(ex, ey, ew, eh, tokens["panel"], tokens["border"])
    cv.text(ex + 10, ey + 8, tr(table, "macro.editor.titleEdit", PROFILES[0][0]),
            tokens["textOnPanel"], bold=True, max_width=ew - 20)
    fx, fw = ex + 10, ew - 20
    cursor_y = ey + 24
    cv.text(fx, cursor_y, tr(table, "macro.editor.name"), tokens["mutedText"])
    cursor_y += 11
    field(cv, fx, cursor_y, fw, 18, MACROS[0][0], tokens, focused=True)
    cursor_y += 24
    half = (fw - 6) // 2
    button(cv, fx, cursor_y, half, 18, tr(table, "macro.type.chat"), tokens, "accent")
    button(cv, fx + half + 6, cursor_y, half, 18, tr(table, "macro.type.command"), tokens)
    cursor_y += 24
    cv.text(fx, cursor_y, tr(table, "macro.editor.content"), tokens["mutedText"])
    cursor_y += 11
    field(cv, fx, cursor_y, fw, 26, MACROS[0][2], tokens)
    cursor_y += 32
    cv.text(fx, cursor_y, tr(table, "macro.editor.interval"), tokens["mutedText"],
            max_width=half)
    cv.text(fx + half + 6, cursor_y, tr(table, "macro.editor.initialDelay"),
            tokens["mutedText"], max_width=half)
    cursor_y += 11
    field(cv, fx, cursor_y, half, 18, "30", tokens)
    field(cv, fx + half + 6, cursor_y, half, 18, "0", tokens)
    cursor_y += 24
    on_label = tr(table, "macro.editor.enabledOn")
    button(cv, fx, cursor_y, fw, 18, on_label, tokens, "accent", align="left")
    cursor_y += 22
    button(cv, fx, cursor_y, half, 20, tr(table, "action.save"), tokens, "accent")
    button(cv, fx + half + 6, cursor_y, half, 20, tr(table, "action.cancel"), tokens)
    cursor_y += 24
    third = (fw - 12) // 3
    button(cv, fx, cursor_y, third, 18, tr(table, "action.duplicate"), tokens)
    button(cv, fx + third + 6, cursor_y, third, 18, tr(table, "action.tryOnce"), tokens)
    button(cv, fx + (third + 6) * 2, cursor_y, third, 18, tr(table, "action.delete"),
           tokens, "danger")
    if cursor_y + 24 < bottom_limit - 12:
        cv.text(fx, cursor_y + 24, tr(table, "macro.editor.hintEdit"), tokens["mutedText"],
                max_width=fw)

    # ---- settings popup ---------------------------------------------------
    if settings_open:
        # mirrors StudioScreen.render: modal scrim, then the popup
        scrim = tokens_scrim()
        cv.veil(0, 0, width, height, scrim)
        w = 210
        h = min(226, max(60, height - HEADER_HEIGHT - FOOTER_HEIGHT - 6))
        x = max(6, width - w - 12)
        y2 = HEADER_HEIGHT + 2
        cv.shadow(x, y2, w, h, composite(tokens["shadow"], tokens["background"]))
        cv.panel(x, y2, w, h, tokens["raisedPanel"], tokens["borderStrong"])
        cv.text(x + 10, y2 + 8, tr(table, "settings.title"), tokens["textOnPanel"], bold=True)
        rows = (("settings.theme", "normal"), ("settings.accent", "normal"),
                ("settings.reducedMotion", "normal"), ("settings.runStatus", "accent"),
                ("action.export", "normal"), ("action.exportSecrets", "danger"),
                ("action.import", "normal"), ("action.diagnostics", "normal"),
                ("settings.f30Note", "normal"))
        ry = y2 + 24
        for key, state in rows:
            if ry + 20 > y2 + h - 4:
                break
            button(cv, x + 10, ry, w - 20, 20, tr(table, key), tokens, state, align="left")
            ry += 22

    # ---- footer -----------------------------------------------------------
    fy = height - FOOTER_HEIGHT
    cv.fill(0, fy, width, FOOTER_HEIGHT, tokens["panel"])
    cv.fill(0, fy, width, 1, tokens["border"])
    budget = tr(table, "footer.budget", 3.0)
    cv.text(10, fy + 6, budget, tokens["mutedText"])
    status_key = shorts_status(hover_toolbar) if hover_toolbar else "run.started"
    cv.text(14 + cv.width(budget), fy + 6, tr(table, status_key), tokens["normalText"])
    return cv


def shorts_status(short_key: str) -> str:
    """Mirrors hoveredToolbarLabel(): hovering a short button shows its full label."""
    return {"action.copyShort": "profile.copy", "action.deleteShort": "action.delete",
            "action.profilesShort": "profile.toggleList", "action.sortShort": "profile.sort",
            "action.settingsShort": "action.settings"}.get(short_key, "run.started")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--lang", default="tr_tr", choices=["tr_tr", "en_us"])
    parser.add_argument("--out", default=str(ROOT / "ui-preview"))
    parser.add_argument("--clip", action="store_true",
                        help="also render ui-preview/studio-walkthrough.gif")
    args = parser.parse_args()

    read_geometry_from_source()          # refuses to draw stale geometry
    table = load(args.lang)
    tokens_all = json.loads(TOKENS.read_text(encoding="utf-8"))
    out = pathlib.Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    shots = [
        ("studio-dark-wide", 640, 360, 3, "DARK/BLUE", False),
        ("studio-dark-wide-settings", 640, 360, 3, "DARK/BLUE", True),
        ("studio-light-wide", 640, 360, 3, "LIGHT/BLUE", False),
        ("studio-dark-narrow", 300, 260, 4, "DARK/BLUE", False),
    ]
    written = []
    for name, w, h, scale, combo, settings in shots:
        cv = draw_screen(w, h, tokens_all[combo], table, scale, settings)
        path = out / f"{name}.png"
        cv.save(path)
        written.append((path, w, h, combo))
        print(f"{path}  ({w}x{h} gui px @ scale {scale}, {combo})")
    if args.clip:
        path = out / "studio-walkthrough.gif"
        frames = build_clip(tokens_all["DARK/BLUE"], table, 640, 360, 2)
        frames[0].save(path, save_all=True, append_images=frames[1:], duration=900, loop=0)
        print(f"{path}  ({len(frames)} frames, {path.stat().st_size // 1024} KB)")
    return 0


def build_clip(tokens, table, width, height, scale):
    """A short, hand-authored sequence of UI states drawn with the same renderer.

    This is an illustration of state transitions, NOT a screen recording: no
    animation curve, no input handling and no Minecraft frame is involved.
    """
    stages = [
        # (caption key, selected card, hovered toolbar short key, settings open)
        ("run.started", 0, None, False),
        ("run.started", 1, None, False),
        ("run.started", 2, "action.deleteShort", False),
        ("action.diagnostics", 2, "action.settingsShort", False),
        ("settings.title", 2, None, True),
    ]
    frames = []
    for _key, selected, hover, settings in stages:
        cv = draw_screen(width, height, tokens, table, scale, settings_open=settings,
                         selected_card=selected, hover_toolbar=hover)
        frames.append(cv.img.convert("P", palette=Image.ADAPTIVE, colors=128))
    return frames


