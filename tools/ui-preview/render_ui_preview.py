#!/usr/bin/env python3
"""Renders a preview of the Chat Macro Studio screen WITHOUT Minecraft.

READ THIS BEFORE LOOKING AT THE OUTPUT
--------------------------------------
This is **not** a screenshot. Nothing here ran inside Minecraft, and no pixel
came from the game's renderer. It is a deterministic drawing produced from three
real inputs:

  1. the palette the shipping ThemeManager actually returns
     (tools/ui-preview/theme-tokens.json, generated by ThemeDump.java and run
     through the offline javac harness),
  2. the geometry constants in the client sources (StudioScreen.HEADER_HEIGHT,
     PROFILE_COLUMN, EDITOR_COLUMN, CARD_GAP, MacroCardWidget.HEIGHT,
     TOGGLE_WIDTH/HEIGHT and the header button widths),
  3. the real translations from assets/chatmacro_studio/lang/*.json.

What it is good for: checking that the palette has contrast, that the columns
fit at a given window size, that long Turkish strings do not overflow, and that
state is readable without colour.

What it is NOT: proof that the screen works. The client layer has never been
compiled against Minecraft - see KNOWN_LIMITATIONS.md.

Usage:
  python3 tools/ui-preview/render_ui_preview.py [--lang tr_tr] [--out DIR]
"""

