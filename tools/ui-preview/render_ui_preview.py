LANG_DIR = ROOT / "src/main/resources/assets/chatmacro_studio/lang"
FONT_PATH = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
FONT_BOLD = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"

# Geometry read out of the client sources (values verified against them).
HEADER_HEIGHT = 44
FOOTER_HEIGHT = 20
PROFILE_COLUMN = 150
EDITOR_COLUMN = 210
CARD_GAP = 4
CARD_HEIGHT = 46          # MacroCardWidget.HEIGHT
ROW_HEIGHT = 30           # ProfileListPanel.ROW_HEIGHT
TOOLBAR_H = 20
TOGGLE_W, TOGGLE_H = 26, 12
HEADER_BUTTON = 62
HEADER_SMALL = 40
PX = 9                    # Minecraft's default font is 9px tall-ish at scale 1


def read_geometry_from_source() -> dict:
    """Re-reads the constants so the preview cannot drift from the code."""
    screen = (ROOT / "src/main/java/dev/chatmacro/studio/client/screen/StudioScreen.java").read_text()
    card = (ROOT / "src/main/java/dev/chatmacro/studio/client/screen/MacroCardWidget.java").read_text()
    want = {
        "HEADER_HEIGHT": HEADER_HEIGHT, "FOOTER_HEIGHT": FOOTER_HEIGHT,
        "PROFILE_COLUMN": PROFILE_COLUMN, "EDITOR_COLUMN": EDITOR_COLUMN,
        "CARD_GAP": CARD_GAP,
    }
    found = {}
    for name, expected in want.items():
        m = re.search(rf"int {name} = (\d+);", screen)
        if not m:
            raise SystemExit(f"could not find {name} in StudioScreen.java")
        found[name] = int(m.group(1))
        if int(m.group(1)) != expected:
            raise SystemExit(f"{name} drifted: source={m.group(1)} preview={expected}")
    m = re.search(r"int HEIGHT = (\d+);", card)
    if not m or int(m.group(1)) != CARD_HEIGHT:
        raise SystemExit("MacroCardWidget.HEIGHT drifted from the preview")
    m = re.search(r"int TOGGLE_WIDTH = (\d+);", card)
    if not m or int(m.group(1)) != TOGGLE_W:
        raise SystemExit("MacroCardWidget.TOGGLE_WIDTH drifted from the preview")
    panel = (ROOT / "src/main/java/dev/chatmacro/studio/client/screen/ProfileListPanel.java").read_text()
    m = re.search(r"int ROW_HEIGHT = (\d+);", panel)
    if not m or int(m.group(1)) != ROW_HEIGHT:
        raise SystemExit("ProfileListPanel.ROW_HEIGHT drifted from the preview")
    return found


def load(lang: str) -> dict:
    data = json.loads((LANG_DIR / f"{lang}.json").read_text(encoding="utf-8"))
    prefix = "chatmacro_studio."
    return {k[len(prefix):]: v for k, v in data.items() if k.startswith(prefix)}


def tr(table: dict, key: str, *args) -> str:
    value = table.get(key, f"<{key}>")
    for arg in args:
        value = value.replace("%s", str(arg), 1)
    return value


