class Canvas:
    def __init__(self, width: int, height: int, scale: int):
        self.scale = scale
        self.img = Image.new("RGB", (width * scale, height * scale), (0, 0, 0))
        self.d = ImageDraw.Draw(self.img)
        self.font = ImageFont.truetype(FONT_PATH, 9 * scale)
        self.bold = ImageFont.truetype(FONT_BOLD, 9 * scale)

    def veil(self, x, y, w, h, color):
        """Intentional alpha: the modal scrim."""
        if w <= 0 or h <= 0:
            return
        s = self.scale
        layer = Image.new("RGBA", (w * s, h * s), color)
        self.img.paste(layer, (x * s, y * s), layer)

    def fill(self, x, y, w, h, color):
        if w <= 0 or h <= 0:
            return
        if len(color) != 7:
            raise SystemExit(f"opaque fill expected, got {color}: "
                             "resolve token alphas with composite() before drawing "
                             "(this is the same mistake a real fill call would make)")
        s = self.scale
        self.d.rectangle([x * s, y * s, (x + w) * s - 1, (y + h) * s - 1], fill=color)

    def border(self, x, y, w, h, color):
        self.fill(x, y, w, 1, color)
        self.fill(x, y + h - 1, w, 1, color)
        self.fill(x, y, 1, h, color)
        self.fill(x + w - 1, y, 1, h, color)

    def panel(self, x, y, w, h, fill, border, corner=3):
        """Mirrors StudioPalette.panel: chamfered corners, 1px border."""
        c = max(0, min(corner, min(w, h) // 2))
        self.fill(x + c, y, w - 2 * c, h, fill)
        self.fill(x, y + c, w, h - 2 * c, fill)
        if c > 1:
            self.fill(x + 1, y + 1, c - 1, c - 1, fill)
            self.fill(x + w - c, y + 1, c - 1, c - 1, fill)
            self.fill(x + 1, y + h - c, c - 1, c - 1, fill)
            self.fill(x + w - c, y + h - c, c - 1, c - 1, fill)
        if border:
            self.border(x, y, w, h, border)

    def shadow(self, x, y, w, h, color):
        self.fill(x + 2, y + h, w, 2, color)
        self.fill(x + w, y + 2, 2, h - 2, color)

    def text(self, x, y, value, color, bold=False, max_width=None):
        font = self.bold if bold else self.font
        if max_width is not None:
            value = ellipsize(self, value, max_width, font)
        self.d.text((x * self.scale, y * self.scale), value, font=font, fill=color)
        return self.width(value, font)

    def width(self, value, font=None):
        return int(self.d.textlength(value, font=font or self.font) / self.scale)

    def centred(self, x, y, w, value, color, bold=False):
        return self.text(x + (w - self.width(value, self.bold if bold else self.font)) // 2,
                         y, value, color, bold)

    def save(self, path):
        self.img.save(path)


def tokens_scrim() -> str:
    """StudioScreen.SCRIM (0xA0000000) as RGBA for the veil."""
    return (0, 0, 0, 0xA0)


def composite(over: str, under: str) -> str:
    """Mirrors Colors.composite(): resolves an #AARRGGBB tint onto an opaque base."""
    def parts(h):
        h = h.lstrip("#")
        if len(h) == 8:
            return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4, 6))
        return (255,) + tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))
    a, r, g, b = parts(over)
    k = a / 255.0
    _, r2, g2, b2 = parts(under)
    mix = lambda x, y: round(x * k + y * (1 - k))
    return "#%02X%02X%02X" % (mix(r, r2), mix(g, g2), mix(b, b2))


def ellipsize(canvas, value, max_width, font=None):
    if canvas.width(value, font) <= max_width:
        return value
    while value and canvas.width(value + "…", font) > max_width:
        value = value[:-1]
    return value + "…"


def button(cv, x, y, w, h, label, tokens, state="normal", align="centre"):
    fill = {"normal": tokens["raisedPanel"], "hover": tokens["accentHover"],
            "accent": tokens["accent"], "danger": tokens["danger"],
            "disabled": tokens["panel"]}[state]
    border = tokens["accent"] if state == "accent" else tokens["borderStrong"]
    cv.shadow(x, y, w, h, composite(tokens["shadow"], tokens["background"]))
    cv.panel(x, y, w, h, fill, border, corner=2)
    color = tokens["disabledText"] if state == "disabled" else tokens["textOnPanel"]
    if state == "accent":
        color = tokens["textOnAccent"]
    if align == "centre":
        cv.centred(x, y + (h - PX) // 2, w, label, color)
    else:
        cv.text(x + 5, y + (h - PX) // 2, label, color, max_width=w - 10)


def field(cv, x, y, w, h, value, tokens, focused=False, hint=""):
    cv.panel(x, y, w, h, tokens["fieldBackground"], tokens["borderStrong"] if focused
             else tokens["border"], corner=1)
    if focused:
        cv.border(x - 1, y - 1, w + 2, h + 2, tokens["focusRing"])
    if value:
        cv.text(x + 4, y + (h - PX) // 2, value, tokens["normalText"], max_width=w - 8)
    elif hint:
        cv.text(x + 4, y + (h - PX) // 2, hint, tokens["disabledText"], max_width=w - 8)


def contrast(a: str, b: str) -> float:
    def lum(h):
        h = h.lstrip("#")[-6:]
        ch = [int(h[i:i + 2], 16) / 255.0 for i in (0, 2, 4)]
        ch = [c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4 for c in ch]
        return 0.2126 * ch[0] + 0.7152 * ch[1] + 0.0722 * ch[2]
    la, lb = lum(a), lum(b)
    hi, lo = max(la, lb), min(la, lb)
    return (hi + 0.05) / (lo + 0.05)


def enforce_contrast(text_color: str, surface: str, minimum: float = 4.5) -> str:
    """Mirrors Colors.enforceContrast: keep the colour, else force black/white."""
    if contrast(text_color, surface) >= minimum:
        return text_color
    return "#000000" if contrast("#000000", surface) >= contrast("#FFFFFF", surface) else "#FFFFFF"


def pill(cv, x, y, h, label, fill, text_color):
    w = cv.width(label) + 12
    cv.panel(x, y, w, h, fill, 0, corner=h // 2)
    cv.text(x + 6, y + (h - PX) // 2, label, enforce_contrast(text_color, fill))
    return w


